//! The Decimal subtype ([MS-VBAL] 2.1, 5.5.1.2.1.3): an unsigned 96-bit integer mantissa, a sign
//! and a power-of-ten scale from 0 to 28. Arithmetic is exact until a result needs more than 96
//! bits or 28 decimal places; then it is rounded half to even, and Overflow is raised when even a
//! scale of 0 cannot hold it.
//!
//! Intermediate results are held as base-10 digit vectors (least significant first), which keeps
//! every operation simple and exact; operands never exceed 29 digits.

use std::cmp::Ordering;
use std::fmt;

use crate::error::{Result, RuntimeError};
use crate::value::{Value, parse_number};

/// Largest scale (decimal places) a Decimal can carry.
pub const MAX_SCALE: u32 = 28;
const MAX_MANTISSA: u128 = (1u128 << 96) - 1;
/// Fractional digits generated by division before rounding (always beyond scale 28).
const DIV_DIGITS: usize = 60;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Decimal {
    neg: bool,
    scale: u8,
    mantissa: u128,
}

type Digits = Vec<u8>;

fn digits_of(mut n: u128) -> Digits {
    let mut d = Vec::new();
    while n > 0 {
        d.push((n % 10) as u8);
        n /= 10;
    }
    d
}

fn trim(d: &mut Digits) {
    while d.last() == Some(&0) {
        d.pop();
    }
}

/// `d * 10^k`.
fn shift(d: &[u8], k: usize) -> Digits {
    let mut out = vec![0; k];
    out.extend_from_slice(d);
    out
}

fn cmp_digits(a: &[u8], b: &[u8]) -> Ordering {
    let len = |d: &[u8]| d.iter().rposition(|&x| x != 0).map_or(0, |i| i + 1);
    let (la, lb) = (len(a), len(b));
    if la != lb {
        return la.cmp(&lb);
    }
    for i in (0..la).rev() {
        match a[i].cmp(&b[i]) {
            Ordering::Equal => {}
            o => return o,
        }
    }
    Ordering::Equal
}

fn add_digits(a: &[u8], b: &[u8]) -> Digits {
    let mut out = Vec::with_capacity(a.len().max(b.len()) + 1);
    let mut carry = 0u8;
    for i in 0..a.len().max(b.len()) {
        let s = a.get(i).copied().unwrap_or(0) + b.get(i).copied().unwrap_or(0) + carry;
        out.push(s % 10);
        carry = s / 10;
    }
    if carry > 0 {
        out.push(carry);
    }
    out
}

/// `a - b` for `a >= b`.
fn sub_digits(a: &[u8], b: &[u8]) -> Digits {
    let mut out = Vec::with_capacity(a.len());
    let mut borrow = 0i8;
    for (i, &x) in a.iter().enumerate() {
        let mut s = x as i8 - b.get(i).copied().unwrap_or(0) as i8 - borrow;
        borrow = 0;
        if s < 0 {
            s += 10;
            borrow = 1;
        }
        out.push(s as u8);
    }
    out
}

fn mul_digits(a: &[u8], b: &[u8]) -> Digits {
    let mut acc = vec![0u32; a.len() + b.len() + 1];
    for (i, &x) in a.iter().enumerate() {
        for (j, &y) in b.iter().enumerate() {
            acc[i + j] += u32::from(x) * u32::from(y);
        }
    }
    let mut carry = 0u32;
    let mut out = Vec::with_capacity(acc.len());
    for v in acc {
        let s = v + carry;
        out.push((s % 10) as u8);
        carry = s / 10;
    }
    while carry > 0 {
        out.push((carry % 10) as u8);
        carry /= 10;
    }
    out
}

fn to_u128(d: &[u8]) -> Option<u128> {
    d.iter().rev().try_fold(0u128, |n, &x| n.checked_mul(10)?.checked_add(u128::from(x)))
}

/// Drops the lowest `drop` digits of `d`, rounding half to even. `sticky` says digits below
/// those in `d` were already discarded and were not all zero.
fn round_off(d: &[u8], drop: usize, sticky: bool) -> Digits {
    if drop == 0 {
        return d.to_vec();
    }
    let digit = |i: usize| d.get(i).copied().unwrap_or(0);
    let mut kept: Digits = d.get(drop..).map(<[u8]>::to_vec).unwrap_or_default();
    let first = digit(drop - 1);
    let rest = sticky || d.iter().take(drop - 1).any(|&x| x != 0);
    let up = first > 5 || (first == 5 && (rest || digit(drop) % 2 == 1));
    if up {
        kept = add_digits(&kept, &[1]);
    }
    kept
}

impl Decimal {
    pub const ZERO: Decimal = Decimal { neg: false, scale: 0, mantissa: 0 };

    /// Builds the Decimal nearest to `±digits / 10^scale`, rounding away digits until the
    /// mantissa fits 96 bits and the scale is at most 28.
    fn fit(neg: bool, mut d: Digits, scale: usize, sticky: bool) -> Result<Decimal> {
        trim(&mut d);
        let mut drop = scale.saturating_sub(MAX_SCALE as usize).max(d.len().saturating_sub(29));
        loop {
            if drop > scale {
                return Err(RuntimeError::overflow());
            }
            let kept = round_off(&d, drop, sticky);
            if let Some(m) = to_u128(&kept).filter(|&m| m <= MAX_MANTISSA) {
                let scale = (scale - drop) as u8;
                return Ok(Decimal { neg: neg && m != 0, scale, mantissa: m });
            }
            drop += 1;
        }
    }

    pub fn from_i64(n: i64) -> Decimal {
        Decimal { neg: n < 0, scale: 0, mantissa: u128::from(n.unsigned_abs()) }
    }

    /// Exact value of a Currency (scaled by 10,000).
    pub fn from_currency(n: i64) -> Decimal {
        Decimal { neg: n < 0, scale: 4, mantissa: u128::from(n.unsigned_abs()) }
    }

    /// A floating value rounded to `significant` digits (15 for Double, 7 for Single), the way
    /// the language converts binary floating point to Decimal.
    pub fn from_f64(x: f64, significant: usize) -> Result<Decimal> {
        if !x.is_finite() {
            return Err(RuntimeError::overflow());
        }
        if x == 0.0 {
            return Ok(Decimal::ZERO);
        }
        let text = format!("{:.*e}", significant.saturating_sub(1), x);
        Decimal::parse(&text).unwrap_or_else(|| Err(RuntimeError::overflow()))
    }

    /// Parses decimal text (sign, digits, one point, optional exponent; spaces, `$`, thousands
    /// separators and accounting parentheses allowed). `None` when the text is not in that form.
    pub fn parse(text: &str) -> Option<Result<Decimal>> {
        let t = text.trim();
        let (paren, body) =
            if let Some(r) = t.strip_prefix('(').and_then(|r| r.strip_suffix(')')) { (true, r) } else { (false, t) };
        let cleaned: String = body.chars().filter(|&c| !matches!(c, ',' | '$') && !c.is_whitespace()).collect();
        let (neg, rest) = match cleaned.as_bytes().first() {
            Some(b'-') => (true, &cleaned[1..]),
            Some(b'+') => (false, &cleaned[1..]),
            _ => (false, cleaned.as_str()),
        };
        let (mant, exp) = match rest.find(['e', 'E', 'd', 'D']) {
            Some(i) => (&rest[..i], Some(&rest[i + 1..])),
            None => (rest, None),
        };
        let exp: i64 = match exp {
            Some(e) => {
                let digits = e.strip_prefix(['+', '-']).unwrap_or(e);
                if digits.is_empty() || !digits.bytes().all(|b| b.is_ascii_digit()) || digits.len() > 9 {
                    return None;
                }
                e.parse().ok()?
            }
            None => 0,
        };
        let (int, frac) = mant.split_once('.').unwrap_or((mant, ""));
        if int.is_empty() && frac.is_empty() {
            return None;
        }
        if !int.bytes().chain(frac.bytes()).all(|b| b.is_ascii_digit()) {
            return None;
        }
        let mut d: Digits = int.bytes().chain(frac.bytes()).rev().map(|b| b - b'0').collect();
        trim(&mut d);
        let neg = neg != paren;
        if d.is_empty() {
            return Some(Ok(Decimal::ZERO));
        }
        let scale = frac.len() as i64 - exp;
        if scale < 0 {
            if (d.len() as i64 - scale) > 29 {
                return Some(Err(RuntimeError::overflow()));
            }
            d = shift(&d, (-scale) as usize);
            return Some(Decimal::fit(neg, d, 0, false));
        }
        Some(Decimal::fit(neg, d, scale as usize, false))
    }

    /// `CDec`: converts any data value.
    pub fn from_value(v: &Value) -> Result<Decimal> {
        Ok(match v {
            Value::Decimal(d) => *d,
            Value::Empty => Decimal::ZERO,
            Value::Boolean(b) => Decimal::from_i64(if *b { -1 } else { 0 }),
            Value::Byte(n) => Decimal::from_i64(i64::from(*n)),
            Value::Integer(n) => Decimal::from_i64(i64::from(*n)),
            Value::Long(n) => Decimal::from_i64(i64::from(*n)),
            Value::LongLong(n) => Decimal::from_i64(*n),
            Value::Single(x) => Decimal::from_f64(f64::from(*x), 7)?,
            Value::Double(x) | Value::Date(x) => Decimal::from_f64(*x, 15)?,
            Value::Currency(n) => Decimal::from_currency(*n),
            Value::String(s) => match Decimal::parse(s) {
                Some(r) => r?,
                None => Decimal::from_f64(parse_number(s).ok_or_else(RuntimeError::type_mismatch)?, 15)?,
            },
            Value::Null => return Err(RuntimeError::standard(94)),
            Value::Object(Some(o)) => return Decimal::from_value(&o.default_value()?),
            Value::Object(None) => return Err(RuntimeError::object_not_set()),
            Value::Error(_) | Value::Array(_) => return Err(RuntimeError::type_mismatch()),
        })
    }

    pub fn is_zero(&self) -> bool {
        self.mantissa == 0
    }

    pub fn is_negative(&self) -> bool {
        self.neg && self.mantissa != 0
    }

    pub fn negate(self) -> Decimal {
        Decimal { neg: !self.neg && self.mantissa != 0, ..self }
    }

    pub fn abs(self) -> Decimal {
        Decimal { neg: false, ..self }
    }

    pub fn to_f64(&self) -> f64 {
        self.to_string().parse().unwrap_or(0.0)
    }

    /// Rounded half to even to `places` decimal places (`Round`).
    pub fn round(self, places: u32) -> Decimal {
        if u32::from(self.scale) <= places {
            return self;
        }
        let drop = (u32::from(self.scale) - places) as usize;
        let kept = round_off(&digits_of(self.mantissa), drop, false);
        // Rounding can only shrink the scale, so the result always fits.
        Decimal::fit(self.neg, kept, places as usize, false).unwrap_or(self)
    }

    /// Integer part toward zero (`Fix`) or toward minus infinity (`Int`).
    pub fn trunc(self, floor: bool) -> Decimal {
        let unit = 10u128.pow(u32::from(self.scale));
        let whole = self.mantissa / unit;
        let has_fraction = !self.mantissa.is_multiple_of(unit);
        let whole = if floor && self.is_negative() && has_fraction { whole + 1 } else { whole };
        Decimal { neg: self.neg && whole != 0, scale: 0, mantissa: whole }
    }

    /// Integer value rounded half to even, raising Overflow outside the 64-bit range.
    pub fn to_i64(&self) -> Result<i64> {
        let r = self.round(0);
        let n = i128::try_from(r.mantissa).map_err(|_| RuntimeError::overflow())?;
        let n = if r.neg { -n } else { n };
        i64::try_from(n).map_err(|_| RuntimeError::overflow())
    }

    fn aligned(a: &Decimal, b: &Decimal) -> (Digits, Digits, usize) {
        let s = a.scale.max(b.scale);
        let da = shift(&digits_of(a.mantissa), usize::from(s - a.scale));
        let db = shift(&digits_of(b.mantissa), usize::from(s - b.scale));
        (da, db, usize::from(s))
    }

    pub fn checked_add(a: Decimal, b: Decimal) -> Result<Decimal> {
        let (da, db, s) = Decimal::aligned(&a, &b);
        if a.neg == b.neg {
            return Decimal::fit(a.neg, add_digits(&da, &db), s, false);
        }
        match cmp_digits(&da, &db) {
            Ordering::Less => Decimal::fit(b.neg, sub_digits(&db, &da), s, false),
            _ => Decimal::fit(a.neg, sub_digits(&da, &db), s, false),
        }
    }

    pub fn checked_sub(a: Decimal, b: Decimal) -> Result<Decimal> {
        Decimal::checked_add(a, Decimal { neg: !b.neg, ..b })
    }

    pub fn checked_mul(a: Decimal, b: Decimal) -> Result<Decimal> {
        let d = mul_digits(&digits_of(a.mantissa), &digits_of(b.mantissa));
        Decimal::fit(a.neg != b.neg, d, usize::from(a.scale) + usize::from(b.scale), false)
    }

    pub fn checked_div(a: Decimal, b: Decimal) -> Result<Decimal> {
        if b.is_zero() {
            return Err(RuntimeError::div_zero());
        }
        if a.is_zero() {
            return Ok(Decimal::ZERO);
        }
        // Long division in base 10: the remainder stays below the 96-bit divisor, so ten times
        // it fits a u128.
        let mut frac = Vec::new();
        let mut r = a.mantissa % b.mantissa;
        while r != 0 && frac.len() < DIV_DIGITS {
            r *= 10;
            frac.push((r / b.mantissa) as u8);
            r %= b.mantissa;
        }
        let mut d: Digits = frac.iter().rev().copied().collect();
        d.extend(digits_of(a.mantissa / b.mantissa));
        let scale = frac.len() as i64 + i64::from(a.scale) - i64::from(b.scale);
        let neg = a.neg != b.neg;
        if scale < 0 {
            return Decimal::fit(neg, shift(&d, (-scale) as usize), 0, r != 0);
        }
        Decimal::fit(neg, d, scale as usize, r != 0)
    }

    /// Exact numeric order.
    pub fn compare(a: &Decimal, b: &Decimal) -> Ordering {
        match (a.is_negative(), b.is_negative()) {
            (false, true) => Ordering::Greater,
            (true, false) => Ordering::Less,
            (neg, _) => {
                let (da, db, _) = Decimal::aligned(a, b);
                let o = cmp_digits(&da, &db);
                if neg { o.reverse() } else { o }
            }
        }
    }
}

/// `CStr` text: plain notation, trailing fraction zeros dropped.
impl fmt::Display for Decimal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let digits = self.mantissa.to_string();
        let scale = usize::from(self.scale);
        let padded =
            if digits.len() <= scale { format!("{}{digits}", "0".repeat(scale + 1 - digits.len())) } else { digits };
        let (int, frac) = padded.split_at(padded.len() - scale);
        let frac = frac.trim_end_matches('0');
        let sign = if self.is_negative() { "-" } else { "" };
        if frac.is_empty() { write!(f, "{sign}{int}") } else { write!(f, "{sign}{int}.{frac}") }
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    fn d(s: &str) -> Decimal {
        Decimal::parse(s).unwrap().unwrap()
    }

    #[test]
    fn arithmetic_is_exact_then_rounds() {
        assert_eq!(Decimal::checked_mul(d("0.1"), d("3")).unwrap().to_string(), "0.3");
        assert_eq!(Decimal::checked_div(d("1"), d("3")).unwrap().to_string(), "0.3333333333333333333333333333");
        assert_eq!(Decimal::checked_div(d("2"), d("3")).unwrap().to_string(), "0.6666666666666666666666666667");
        assert_eq!(Decimal::checked_div(d("100"), d("0.25")).unwrap().to_string(), "400");
        let seventh = Decimal::checked_div(d("1"), d("7")).unwrap();
        assert_eq!(Decimal::checked_mul(seventh, d("7")).unwrap().to_string(), "1.0000000000000000000000000003");
        assert!(Decimal::checked_add(d("79228162514264337593543950335"), d("1")).is_err());
        assert_eq!(d("1.23456789012345678901234567890").to_string(), "1.2345678901234567890123456789");
        assert_eq!(d("-0").to_string(), "0");
        assert_eq!(d("1.5E-3").to_string(), "0.0015");
    }

    #[test]
    fn rounding_and_conversion() {
        assert_eq!(d("2.345").round(2).to_string(), "2.34");
        assert_eq!(d("2.355").round(2).to_string(), "2.36");
        assert_eq!(d("-2.5").trunc(true).to_string(), "-3");
        assert_eq!(d("-2.5").trunc(false).to_string(), "-2");
        assert_eq!(d("2.5").to_i64().unwrap(), 2);
        assert_eq!(Decimal::from_f64(123456789.123456, 15).unwrap().to_string(), "123456789.123456");
        assert_eq!(Decimal::from_f64(1e20, 15).unwrap().to_string(), "100000000000000000000");
        assert_eq!(Decimal::compare(&d("1.10"), &d("1.1")), Ordering::Equal);
    }
}
