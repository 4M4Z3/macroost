/// The value of the enumeration constant `name` (case-insensitive).
pub fn constant(name: &str) -> Option<i32> {
    CONSTANTS.iter().find(|(n, _)| n.eq_ignore_ascii_case(name)).map(|(_, v)| *v)
}

#[cfg(test)]
mod tests {
    #[test]
    fn names_are_unique() {
        for (i, (a, _)) in super::CONSTANTS.iter().enumerate() {
            assert!(!super::CONSTANTS[..i].iter().any(|(b, _)| b.eq_ignore_ascii_case(a)), "{a}");
        }
    }
}
